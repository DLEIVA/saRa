const assert=require('node:assert/strict');
const root=require('node:path').resolve(__dirname,'../..')+'/';
const cat=require(root+'jamovi/js/catsummary.js');
const ord=require(root+'jamovi/js/ordsummary.js');
const item=(name,measure,data='text')=>({value:{raw:name},properties:{measureType:measure,dataType:data}});
const control=value=>({v:value,value(){return this.v},setValue(value){this.v=value},setPropertyValue(name,value){this[name]=value}});
const nominal=control([item('n','nominal'),item('o','ordinal'),item('c','continuous')]);
cat.view_loaded({nominalSupplier:nominal});
assert.deepEqual(nominal.value().map(x=>x.value.raw),['n']);
const ui={vars:control(['text']),ordinalSupplier:control([item('text','ordinal'),item('number','ordinal','integer'),item('nominal','nominal')]),range:control(true)};
ord.view_loaded(ui);
assert.equal(ui.range.value(),false);
assert.equal(ui.range.enable,false);
assert.equal(ui.ordinalSupplier.value().length,2);
ui.vars.setValue(['number']); ord.vars_changed(ui);
assert.equal(ui.range.value(),true);
assert.equal(ui.range.enable,true);
ui.range.setValue(false); ord.view_updated(ui); assert.equal(ui.range.value(),false);
const saved={vars:control(['number']),ordinalSupplier:control([item('number','ordinal','decimal')]),range:control(false)};
ord.view_loaded(saved); assert.equal(saved.range.value(),false);
console.log('PASS: nominal supplier, ordinal supplier, text-to-numeric Range transition, manual-off and saved-off numeric Range');
